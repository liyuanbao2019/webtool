package com.li.jc.webtool.service.dataimport;

import lombok.Data;

import java.sql.Types;

/** Target table column metadata used for mapping and value conversion. */
@Data
public class ImportColumn {
    private String name;
    private String typeName;
    private int jdbcType;
    private int size;
    private int decimalDigits;
    private boolean nullable = true;
    private String defaultValue;
    private boolean autoIncrement;
    private boolean primaryKey;
    private String remarks;

    /** Binary columns cannot be filled from text. */
    public boolean isImportable() {
        switch (jdbcType) {
            case Types.BINARY:
            case Types.VARBINARY:
            case Types.LONGVARBINARY:
            case Types.BLOB:
                return false;
            default:
                return true;
        }
    }

    /** A NOT NULL column that has no default and is not generated by the database. */
    public boolean isRequired() {
        return !nullable && !autoIncrement && (defaultValue == null || defaultValue.trim().isEmpty());
    }

    public boolean isCharacterType() {
        switch (jdbcType) {
            case Types.CHAR:
            case Types.VARCHAR:
            case Types.NCHAR:
            case Types.NVARCHAR:
            case Types.LONGVARCHAR:
            case Types.LONGNVARCHAR:
            case Types.CLOB:
            case Types.NCLOB:
                return true;
            default:
                return false;
        }
    }

    /** Length limit worth checking before insert; 0 when unknown or effectively unlimited. */
    public int checkedLength() {
        switch (jdbcType) {
            case Types.CHAR:
            case Types.VARCHAR:
            case Types.NCHAR:
            case Types.NVARCHAR:
                return size > 0 && size < 1_000_000 ? size : 0;
            default:
                return 0;
        }
    }

    public String displayType() {
        String base = typeName == null ? String.valueOf(jdbcType) : typeName;
        if (checkedLength() > 0) {
            return base + "(" + size + ")";
        }
        if ((jdbcType == Types.DECIMAL || jdbcType == Types.NUMERIC) && size > 0) {
            return decimalDigits > 0 ? base + "(" + size + "," + decimalDigits + ")" : base + "(" + size + ")";
        }
        return base;
    }
}
